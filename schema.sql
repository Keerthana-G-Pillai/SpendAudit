-- Supabase Database Schema

-- 1. Create audits table (if not already present)
CREATE TABLE IF NOT EXISTS public.audits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  spend_data JSONB NOT NULL,
  audit_result JSONB NOT NULL,
  ai_summary TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Create leads table (missing in Supabase instance)
CREATE TABLE IF NOT EXISTS public.leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  audit_id BIGINT REFERENCES public.audits(id) ON DELETE SET NULL,
  email TEXT NOT NULL,
  company TEXT,
  role TEXT,
  team_size INTEGER,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.audits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;

-- 4. Define Security Policies
-- Allow anyone (public anon/authenticated) to read audits by their slug or ID for shareable results pages
CREATE POLICY "Allow public read access to audits" ON public.audits
  FOR SELECT TO anon, authenticated USING (true);

-- No public policies for 'leads'. All inserts are performed via Next.js API routes
-- using the service_role key which bypasses RLS, ensuring private email capture remains strictly server-side.

