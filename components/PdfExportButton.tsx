'use client'

import { useState } from 'react'
import type { AuditResult, ToolRecommendation } from '@/lib/types'

interface Props {
  auditResult: AuditResult
  aiSummary: string
}

export default function PdfExportButton({ auditResult, aiSummary }: Props) {
  const [generating, setGenerating] = useState(false)

  const handleExport = async () => {
    setGenerating(true)
    try {
      const { jsPDF } = await import('jspdf')
      const doc = new jsPDF()
      const pageWidth = doc.internal.pageSize.getWidth()
      let y = 20

      // ── Title ──
      doc.setFontSize(22)
      doc.setFont('helvetica', 'bold')
      doc.text('AI Spend Audit Report', pageWidth / 2, y, { align: 'center' })
      y += 12

      // ── Savings hero ──
      doc.setFontSize(14)
      doc.setFont('helvetica', 'normal')
      if (auditResult.totalMonthlySavings === 0) {
        doc.text('Your AI stack is well-optimized. No savings found.', pageWidth / 2, y, { align: 'center' })
      } else {
        doc.text(
          `Potential savings: $${auditResult.totalMonthlySavings}/mo ($${auditResult.totalAnnualSavings.toLocaleString()}/yr)`,
          pageWidth / 2, y, { align: 'center' }
        )
      }
      y += 6
      doc.setFontSize(10)
      doc.setTextColor(120)
      doc.text(`Current total spend: $${auditResult.totalCurrentSpend}/mo`, pageWidth / 2, y, { align: 'center' })
      doc.setTextColor(0)
      y += 12

      // ── Divider ──
      doc.setDrawColor(200)
      doc.line(20, y, pageWidth - 20, y)
      y += 10

      // ── AI Summary ──
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('AI Analysis', 20, y)
      y += 7
      
      const paragraphs = aiSummary.split('\n').filter(p => p.trim() !== '')
      for (const p of paragraphs) {
        if (p.trim().startsWith('**') && p.trim().endsWith('**')) {
          doc.setFont('helvetica', 'bold')
          doc.setFontSize(11)
          const text = p.trim().substring(2, p.trim().length - 2)
          const headingLines = doc.splitTextToSize(text, pageWidth - 40)
          doc.text(headingLines, 20, y)
          y += headingLines.length * 5 + 2
        } else {
          doc.setFont('helvetica', 'normal')
          doc.setFontSize(10)
          const cleanText = p.replace(/\*\*/g, '')
          const textLines = doc.splitTextToSize(cleanText, pageWidth - 40)
          doc.text(textLines, 20, y)
          y += textLines.length * 5 + 3
        }
      }
      y += 7

      // ── Divider ──
      doc.line(20, y, pageWidth - 20, y)
      y += 10

      // ── Per-tool breakdown ──
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('Breakdown by Tool', 20, y)
      y += 8

      auditResult.recommendations.forEach((rec: ToolRecommendation) => {
        // Check if we need a new page
        if (y > 260) {
          doc.addPage()
          y = 20
        }

        const name = rec.tool.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())

        doc.setFontSize(11)
        doc.setFont('helvetica', 'bold')
        doc.text(name, 20, y)

        const savingText = rec.estimatedMonthlySaving > 0
          ? `Save $${rec.estimatedMonthlySaving}/mo`
          : 'Optimal'
        doc.setFont('helvetica', 'normal')
        doc.text(savingText, pageWidth - 20, y, { align: 'right' })
        y += 5

        doc.setFontSize(9)
        doc.setTextColor(80)
        doc.text(`Current spend: $${rec.currentSpend}/mo`, 24, y)
        y += 4

        const actionLines = doc.splitTextToSize(rec.recommendedAction, pageWidth - 48)
        doc.text(actionLines, 24, y)
        y += actionLines.length * 4 + 2

        const reasonLines = doc.splitTextToSize(rec.reasoning, pageWidth - 48)
        doc.setTextColor(120)
        doc.text(reasonLines, 24, y)
        y += reasonLines.length * 4 + 8
        doc.setTextColor(0)
      })

      // ── Footer ──
      const finalY = Math.min(y + 10, 280)
      doc.setFontSize(8)
      doc.setTextColor(150)
      doc.text('Generated by AI Spend Audit — credex.rocks', pageWidth / 2, finalY, { align: 'center' })

      doc.save('ai-spend-audit.pdf')
    } catch (err) {
      console.error('PDF generation failed:', err)
    } finally {
      setGenerating(false)
    }
  }

  return (
    <button
      type="button"
      onClick={handleExport}
      disabled={generating}
      aria-label="Download audit as PDF"
      className="ui-btn-secondary w-full h-10 gap-2 disabled:opacity-50"
    >
      <span aria-hidden="true">📄</span>
      <span>{generating ? 'Generating PDF...' : 'Download PDF report'}</span>
    </button>
  )
}
