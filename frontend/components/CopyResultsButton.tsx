'use client'

import { useState } from 'react'
import type { AuditResult, ToolRecommendation } from '@backend/lib/types'

interface Props {
  auditResult: AuditResult
}

function formatAsText(result: AuditResult): string {
  const lines: string[] = [
    '🔍 AI Spend Audit Results',
    '━━━━━━━━━━━━━━━━━━━━━━━━',
    '',
    `💰 Total potential savings: $${result.totalMonthlySavings}/mo ($${result.totalAnnualSavings.toLocaleString()}/yr)`,
    `📊 Current total spend: $${result.totalCurrentSpend}/mo`,
    '',
    '📋 Breakdown:',
  ]

  result.recommendations.forEach((rec: ToolRecommendation) => {
    const name = rec.tool.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
    if (rec.estimatedMonthlySaving > 0) {
      lines.push(`  • ${name} ($${rec.currentSpend}/mo) → Save $${rec.estimatedMonthlySaving}/mo`)
      lines.push(`    ${rec.recommendedAction}`)
    } else {
      lines.push(`  • ${name} ($${rec.currentSpend}/mo) → ✓ Optimal`)
    }
  })

  lines.push('')
  lines.push('—')
  lines.push('Generated by AI Spend Audit · credex.rocks')

  return lines.join('\n')
}

export default function CopyResultsButton({ auditResult }: Props) {
  const [copied, setCopied] = useState(false)

  const handleCopy = async () => {
    const text = formatAsText(auditResult)
    try {
      await navigator.clipboard.writeText(text)
      setCopied(true)
      setTimeout(() => setCopied(false), 2500)
    } catch {
      window.prompt('Copy your audit results:', text)
    }
  }

  return (
    <button
      type="button"
      onClick={handleCopy}
      aria-label={copied ? 'Results copied' : 'Copy results as text'}
      className="w-full min-h-[48px] border border-gray-200 rounded-xl py-3 text-sm font-medium text-gray-600 hover:bg-gray-50 hover:border-gray-300 transition flex items-center justify-center gap-2 focus:outline-none focus:ring-2 focus:ring-gray-900 focus:ring-offset-2"
    >
      {copied ? (
        <>
          <span aria-hidden="true">✓</span>
          <span>Copied to clipboard</span>
        </>
      ) : (
        <>
          <span aria-hidden="true">📋</span>
          <span>Copy results for Slack / email</span>
        </>
      )}
    </button>
  )
}
